#!/usr/bin/env python3
"""Run the reproducible Quran analysis and generate website data artifacts."""
from __future__ import annotations

import argparse
import json
import os
import re
from pathlib import Path

from scientific_quran_analyzer import (
    DEFAULT_SAMPLES,
    DEFAULT_SEED,
    ScientificQuranAnalyzer,
    SimulationConfig,
)

ROOT = Path(__file__).resolve().parents[1]
DATA_JS = ROOT / "quran-analysis" / "data.js"
REPORT_PATH = ROOT / "analysis" / "quran_analysis_report.json"
NODE_METRICS_PATH = ROOT / "semver-bnf" / "quran-node-metrics.mjs"


def load_surahs() -> list[tuple[int, str, int]]:
    source = DATA_JS.read_text(encoding="utf-8")
    match = re.search(r"const SURAHS = (\[.*?\]);", source, flags=re.DOTALL)
    if not match:
        raise RuntimeError(f"Could not find SURAHS JSON in {DATA_JS}")
    rows = json.loads(match.group(1))
    return [(int(row["number"]), str(row["name"]), int(row["ayahs"])) for row in rows]


def write_node_metrics(report: dict) -> None:
    fields = (
        "surah_number", "surah_name", "ayahs_count", "type",
        "surah_number_root", "ayahs_count_root", "combined_value",
        "combined_root", "abjad_value", "abjad_root",
    )
    rows = [{field: row[field] for field in fields} for row in report["rows"]]
    content = (
        "// Generated by analysis/run_reproducible_pipeline.py. Do not edit by hand.\n"
        "// The 114 surah records are deterministically cycled across the 6600 nodes.\n"
        f"export const QURAN_SURAH_METRICS = {json.dumps(rows, ensure_ascii=False, separators=(',', ':'))};\n"
        f"export const QURAN_STATISTICS = {json.dumps({'tests': report['tests'], 'kruskal_wallis': report['kruskal_wallis']}, ensure_ascii=False, separators=(',', ':'))};\n"
        "export function quranMetricForNode(id) { return QURAN_SURAH_METRICS[(Number(id) - 1) % QURAN_SURAH_METRICS.length]; }\n"
    )
    NODE_METRICS_PATH.write_text(content, encoding="utf-8")


def write_summary(report: dict) -> None:
    summary_target = os.environ.get("GITHUB_STEP_SUMMARY")
    if not summary_target:
        return
    summary_path = Path(summary_target)
    lines = [
        "## Quran reproducible analysis",
        "",
        f"- Surahs: **{report['metadata']['total_surahs']}** (Madani: **{report['metadata']['civil_surahs']}**)",
        f"- Monte Carlo: **B={report['metadata']['simulations_B']:,}**, seed **{report['metadata']['random_seed']}**, **{report['metadata']['rng_algorithm']}**",
        "",
        "| Test | χ² | p (Monte Carlo) | SE |",
        "|---|---:|---:|---:|",
    ]
    for name, item in report["tests"].items():
        metrics = item["statistical_metrics"]
        lines.append(f"| `{name}` | {metrics['chi2_observed']:.6f} | {metrics['p_value_monte_carlo']:.6f} | {metrics['standard_error_se']:.6f} |")
    lines += ["", "| Kruskal-Wallis | H | p | ε² |", "|---|---:|---:|---:|"]
    for name, item in report["kruskal_wallis"].items():
        metrics = item["statistical_metrics"]
        lines.append(f"| `{name}` | {metrics['H_statistic']:.6f} | {metrics['p_value']:.6f} | {metrics['epsilon_squared']:.6f} |")
    summary_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", type=int, default=DEFAULT_SAMPLES)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()
    if args.seed != DEFAULT_SEED:
        raise SystemExit(f"CI policy requires seed={DEFAULT_SEED}, got {args.seed}")
    if args.samples < 1:
        raise SystemExit("samples must be positive")

    report = ScientificQuranAnalyzer(load_surahs()).build_report(
        SimulationConfig(samples=args.samples, seed=args.seed)
    )
    if report["metadata"]["total_surahs"] != 114:
        raise SystemExit("Expected exactly 114 surahs")
    if set(report["kruskal_wallis"]) != {"surah_number", "ayahs_count", "combined_value", "abjad_value"}:
        raise SystemExit("Kruskal-Wallis coverage is incomplete")
    REPORT_PATH.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_node_metrics(report)
    write_summary(report)
    combined = report["tests"]["combined_root"]["statistical_metrics"]
    print(f"Generated {REPORT_PATH}")
    print(f"Generated {NODE_METRICS_PATH}")
    print(f"combined_root p={combined['p_value_monte_carlo']:.8f} se={combined['standard_error_se']:.8f}")
    print(f"combined_value Kruskal-Wallis p={report['kruskal_wallis']['combined_value']['statistical_metrics']['p_value']:.8f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
