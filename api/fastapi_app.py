"""FastAPI JSON service for the reproducible Quran statistical report.

Run locally from the repository root:
    uvicorn api.fastapi_app:app --reload --port 8000

The service is intentionally read-only. It serves the report generated by
analysis/run_reproducible_pipeline.py and never runs a simulation per request.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware

ROOT = Path(__file__).resolve().parents[1]
REPORT_PATH = Path(os.getenv("QURAN_REPORT_PATH", ROOT / "analysis" / "quran_analysis_report.json"))
API_VERSION = "1.0.0"

app = FastAPI(
    title="Azzouz Quran Statistical API",
    version=API_VERSION,
    description="Read-only JSON API for Kruskal-Wallis results and multiple-comparison corrections.",
)

allowed_origins = [origin.strip() for origin in os.getenv("QURAN_API_CORS_ORIGINS", "").split(",") if origin.strip()]
if allowed_origins:
    app.add_middleware(
        CORSMiddleware,
        allow_origins=allowed_origins,
        allow_credentials=False,
        allow_methods=["GET"],
        allow_headers=["*"],
    )


def load_report() -> dict[str, Any]:
    try:
        return json.loads(REPORT_PATH.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise HTTPException(status_code=503, detail=f"Report not found: {REPORT_PATH}") from exc
    except json.JSONDecodeError as exc:
        raise HTTPException(status_code=503, detail="The Quran report is not valid JSON") from exc


def result_payload(name: str, item: dict[str, Any], alpha: float) -> dict[str, Any]:
    metrics = item["statistical_metrics"]
    correction = item.get("multiple_comparison", {})
    return {
        "feature": name,
        "test": item.get("test", "Kruskal-Wallis H"),
        "groups": item.get("groups", {}),
        "H_statistic": metrics["H_statistic"],
        "degrees_of_freedom": metrics["degrees_of_freedom"],
        "raw_p_value": metrics["p_value"],
        "epsilon_squared": metrics["epsilon_squared"],
        "multiple_comparison": {
            "alpha": alpha,
            "p_holm": correction.get("p_holm"),
            "p_benjamini_hochberg": correction.get("p_benjamini_hochberg"),
            "reject_holm": bool(correction.get("p_holm", 1) <= alpha),
            "reject_benjamini_hochberg": bool(correction.get("p_benjamini_hochberg", 1) <= alpha),
        },
    }


@app.get("/api/v1/health")
def health() -> dict[str, Any]:
    report = load_report()
    return {
        "status": "ok",
        "api_version": API_VERSION,
        "report_path": str(REPORT_PATH),
        "report_timestamp_utc": report["metadata"].get("timestamp_utc"),
        "total_surahs": report["metadata"].get("total_surahs"),
    }


@app.get("/api/v1/kruskal-wallis")
def kruskal_wallis(
    alpha: float = Query(0.05, gt=0, lt=1, description="Significance level used for reject decisions"),
) -> dict[str, Any]:
    report = load_report()
    results = {
        name: result_payload(name, item, alpha)
        for name, item in report.get("kruskal_wallis", {}).items()
    }
    correction = report.get("multiple_comparison", {})
    return {
        "api_version": API_VERSION,
        "analysis": "Kruskal-Wallis across Makki/Madani groups",
        "alpha": alpha,
        "correction_methods": correction.get("methods", ["Holm step-down", "Benjamini-Hochberg"]),
        "report_metadata": report.get("metadata", {}),
        "results": results,
    }


@app.get("/api/v1/kruskal-wallis/{feature}")
def kruskal_wallis_feature(
    feature: str,
    alpha: float = Query(0.05, gt=0, lt=1, description="Significance level used for reject decisions"),
) -> dict[str, Any]:
    report = load_report()
    item = report.get("kruskal_wallis", {}).get(feature)
    if item is None:
        raise HTTPException(
            status_code=404,
            detail={
                "message": "Unknown Kruskal-Wallis feature",
                "allowed_features": sorted(report.get("kruskal_wallis", {})),
            },
        )
    return {
        "api_version": API_VERSION,
        "alpha": alpha,
        "correction_methods": report.get("multiple_comparison", {}).get("methods", []),
        "result": result_payload(feature, item, alpha),
    }


@app.get("/api/v1/report")
def report_metadata() -> dict[str, Any]:
    """Return the full reproducibility metadata without raw row data."""
    report = load_report()
    return {
        "api_version": API_VERSION,
        "metadata": report.get("metadata", {}),
        "multiple_comparison": report.get("multiple_comparison", {}),
        "features": sorted(report.get("kruskal_wallis", {})),
    }
