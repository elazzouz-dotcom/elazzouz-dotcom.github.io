#!/usr/bin/env python3
"""Generate a D1-compatible SQL seed for the 6600-node hierarchy.

The generated records are intentionally empty knowledge records. Real source
URLs/content should be added through the protected POST /api/nodes endpoint.
"""
from pathlib import Path

TOTAL = 6600
OUT = Path(__file__).with_name("0002_seed_nodes.sql")

def esc(value: str) -> str:
    return value.replace("'", "''")

rows = []
for node_id in range(1, TOTAL + 1):
    parent = node_id - 1 if node_id > 1 else None
    key = f"N-{node_id:03d}"
    title = f"عقدة {key}"
    description = "عقدة معرفة جاهزة لإضافة مصدر ومحتوى."
    parent_sql = "NULL" if parent is None else str(parent)
    rows.append(
        "INSERT OR IGNORE INTO nodes "
        "(id,node_key,title,description,language,domain,status,source_type,parent_id) VALUES "
        f"({node_id},'{esc(key)}','{esc(title)}','{esc(description)}','ar','general','active','web',{parent_sql});"
    )

OUT.write_text("-- Generated by seed_nodes.py\n" + "\n".join(rows) + "\n", encoding="utf-8")
print(f"wrote {len(rows)} nodes to {OUT}")
